#!/usr/bin/env node
/**
 * gen-ipc.mjs — the contract code generator (Gilde 2 contract §3.1, §4.1; C1).
 *
 * One source of truth: the Rust types under `src-tauri/src/contract/` (ts-rs)
 * and the command/event manifest `src-tauri/src/contract/ipc_manifest.rs`.
 * From them this script writes, deterministically:
 *
 *   src/lib/gen/<Type>.ts            every contract type (ids branded)
 *   src/lib/gen/commands.ts          one typed wrapper per command (invoke("<name>", { req }))
 *   src/lib/gen/events.ts            the four global events (listen only)
 *   src/lib/gen/index.ts             barrel
 *   src/lib/gen/tsconfig.json        isolated type check of the generated files
 *   src-tauri/sidecar/src/gen/**     the same type files for the sidecar (no Tauri imports)
 *   src-tauri/src/commands/registry.rs   the generate_handler! list
 *   src-tauri/capabilities/main.json     core permissions + allow-<command> for the main list
 *   src-tauri/capabilities/debug.json    the debug-only commands (debug builds only, build.rs)
 *
 * How: `cargo test --features ts-export --lib export_bindings` with
 * TS_RS_EXPORT_DIR and GILDE_IPC_MANIFEST_OUT pointing into a temp dir, then
 * post-processing. Output has no timestamps and no absolute paths, so running
 * it twice produces no diff.
 *
 *   node scripts/gen-ipc.mjs              regenerate everything
 *   node scripts/gen-ipc.mjs --check      regenerate into a temp dir; exit 1 on any drift
 *   node scripts/gen-ipc.mjs --typecheck  also run tsc over src/lib/gen in isolation
 *   node scripts/gen-ipc.mjs --manifest <file.json>
 *                                         Rust-side outputs only (registry, capabilities)
 *                                         from a manifest JSON, without running cargo
 */

import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdtempSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const typecheck = args.includes('--typecheck');
const manifestArg = args.includes('--manifest') ? args[args.indexOf('--manifest') + 1] : null;

const GEN_TS = 'src/lib/gen';
const GEN_SIDECAR = 'src-tauri/sidecar/src/gen';
const REGISTRY = 'src-tauri/src/commands/registry.rs';
const CAP_MAIN = 'src-tauri/capabilities/main.json';
const CAP_DEBUG = 'src-tauri/capabilities/debug.json';

const TS_HEADER =
  '// GENERATED by scripts/gen-ipc.mjs (cargo test --features ts-export export_bindings) from\n' +
  '// src-tauri/src/contract/. Do not edit.\n';

/** §3.2 identifiers: branded so two ids of different kinds never mix. */
const BRANDED = [
  'ProjectId', 'LocationId', 'AccountId', 'SessionUid', 'TeamKey', 'MemberKey', 'TaskKey',
  'MessageKey', 'ProcessKey', 'PtyId', 'PaneId', 'RequestId', 'ClientMsgId', 'ClientRequestId',
  'EpisodeId', 'BlockId', 'QuitRecordId', 'ConfirmToken', 'UndoToken', 'SubId', 'ViewId',
  'QueryId', 'HistoryCursor',
];

const die = (msg) => {
  console.error(`[gen-ipc] ${msg}`);
  process.exit(1);
};

// ---------------------------------------------------------------------------
// 1. raw material: ts-rs files + the manifest
// ---------------------------------------------------------------------------

function runCargo(work) {
  const tsDir = join(work, 'ts');
  mkdirSync(tsDir, { recursive: true });
  const manifestOut = join(work, 'manifest.json');
  try {
    execFileSync(
      'cargo',
      [
        'test',
        '--manifest-path', join(root, 'src-tauri', 'Cargo.toml'),
        '--features', 'ts-export',
        '--lib',
        'export_bindings',
        '--',
        '--test-threads=1',
      ],
      {
        cwd: join(root, 'src-tauri'),
        env: {
          ...process.env,
          TS_RS_EXPORT_DIR: tsDir,
          GILDE_IPC_MANIFEST_OUT: manifestOut,
          CARGO_TERM_COLOR: 'never',
        },
        stdio: ['ignore', 'ignore', 'inherit'],
      },
    );
  } catch (err) {
    die(`cargo test --features ts-export export_bindings failed (${err.status ?? err.message})`);
  }
  if (!existsSync(manifestOut)) die('the manifest export test did not write its JSON');
  return { tsDir, manifest: JSON.parse(readFileSync(manifestOut, 'utf8')) };
}

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

// ---------------------------------------------------------------------------
// 2. post-processing of the type files
// ---------------------------------------------------------------------------

function processType(rel, text) {
  let body = text.replace(/^\/\/ This file was generated by \[ts-rs\][^\n]*\n/, '');
  const name = rel.replace(/\.ts$/, '').split('/').pop();
  if (BRANDED.includes(name)) {
    const plain = `export type ${name} = string;`;
    if (!body.includes(plain)) die(`expected ${rel} to be a plain string id, found: ${body.trim()}`);
    body = body.replace(plain, `export type ${name} = string & { readonly __brand: "${name}" };`);
  }
  return TS_HEADER + body.replace(/\r\n/g, '\n').replace(/\n*$/, '\n');
}

// ---------------------------------------------------------------------------
// 3. commands.ts, events.ts, index.ts, tsconfig.json
// ---------------------------------------------------------------------------

function errorsDoc(c) {
  const list = c.errors.map((e) => (e.params.length ? `${e.code}{${e.params.join('|')}}` : e.code));
  return list.length ? list.join(', ') : 'common codes only';
}

function commandsTs(manifest) {
  const types = new Set(['IpcError']);
  for (const c of manifest.commands) {
    types.add(c.req);
    if (c.res !== 'raw') types.add(c.res);
    if (c.channel) types.add(c.channel);
  }
  const imports = [...types].sort().map((t) => `import type { ${t} } from "./${t}";`).join('\n');
  const names = manifest.commands.map((c) => `  | "${c.name}"`).join('\n');
  const fns = manifest.commands
    .map((c) => {
      const res = c.res === 'raw' ? 'ArrayBuffer' : c.res;
      const params = c.channel ? `req: ${c.req}, channel: Channel<${c.channel}>` : `req: ${c.req}`;
      const payload = c.channel ? '{ req, channel }' : '{ req }';
      const doc = [
        `/**`,
        ` * \`${c.name}\` (contract §${c.section}; ${c.owner}). Rate class \`${c.rate}\`;` +
          ` idempotency \`${c.idempotency}\`; capability \`${c.capability}\`.`,
        ` * Errors beyond INVALID_ARGUMENT, NOT_FOUND, INTERNAL, BUSY: ${errorsDoc(c)}.`,
        ` */`,
      ].join('\n');
      return `${doc}\nexport function ${c.name}(${params}): Promise<${res}> {\n  return invoke<${res}>("${c.name}", ${payload});\n}\n`;
    })
    .join('\n');
  return (
    `// GENERATED by scripts/gen-ipc.mjs from src-tauri/src/contract/ipc_manifest.rs. Do not edit.\n` +
    `// The only way the WebView calls the core (contract §4.1 rule 1). A rejected\n` +
    `// promise always carries the one error shape, IpcError (§4.4).\n` +
    `import { invoke } from "@tauri-apps/api/core";\n` +
    `import type { Channel } from "@tauri-apps/api/core";\n` +
    `${imports}\n\n` +
    `/** Every command of the manifest. */\nexport type CommandName =\n${names};\n\n` +
    `export const COMMAND_NAMES: readonly CommandName[] = [\n${manifest.commands.map((c) => `  "${c.name}",`).join('\n')}\n];\n\n` +
    `/** Narrow an invoke rejection to the contract error shape. */\n` +
    `export function isIpcError(value: unknown): value is IpcError {\n` +
    `  if (typeof value !== "object" || value === null) return false;\n` +
    `  const v = value as Record<string, unknown>;\n` +
    `  return typeof v.code === "string" && typeof v.key === "string" &&\n` +
    `    typeof v.params === "object" && v.params !== null && typeof v.retryable === "boolean";\n` +
    `}\n\n` +
    fns
  );
}

function eventsTs(manifest) {
  const imports = [...new Set(manifest.events.map((e) => e.payload))]
    .sort()
    .map((t) => `import type { ${t} } from "./${t}";`)
    .join('\n');
  const names = manifest.events
    .map((e) => `  ${e.ident.charAt(0).toLowerCase()}${e.ident.slice(1)}: "${e.name}",`)
    .join('\n');
  const fns = manifest.events
    .map(
      (e) =>
        `/** \`${e.name}\`: ${e.when}. */\n` +
        `export function on${e.ident}(handler: (payload: ${e.payload}) => void): Promise<UnlistenFn> {\n` +
        `  return listen<${e.payload}>("${e.name}", (event) => handler(event.payload));\n` +
        `}\n`,
    )
    .join('\n');
  return (
    `// GENERATED by scripts/gen-ipc.mjs from src-tauri/src/contract/ipc_manifest.rs. Do not edit.\n` +
    `// The four global events (contract §4.3). The WebView only listens: it\n` +
    `// cannot emit (core:event:allow-emit is not granted, §9.2).\n` +
    `import { listen } from "@tauri-apps/api/event";\n` +
    `import type { UnlistenFn } from "@tauri-apps/api/event";\n` +
    `${imports}\n\n` +
    `export const EVENT_NAMES = {\n${names}\n} as const;\n\n` +
    fns
  );
}

function indexTs(typeFiles, withTauri) {
  const lines = typeFiles
    .map((rel) => rel.replace(/\.ts$/, ''))
    .map((p) => `export type { ${p.split('/').pop()} } from "./${p}";`);
  if (withTauri) lines.push('export * from "./commands";', 'export * from "./events";');
  return TS_HEADER + lines.join('\n') + '\n';
}

const GEN_TSCONFIG = {
  compilerOptions: {
    target: 'ES2020',
    lib: ['ES2020', 'DOM'],
    module: 'ESNext',
    moduleResolution: 'bundler',
    strict: true,
    noEmit: true,
    isolatedModules: true,
    skipLibCheck: true,
    noUnusedLocals: true,
    noUnusedParameters: true,
    noUncheckedIndexedAccess: true,
    types: [],
  },
  include: ['./**/*.ts'],
};

// ---------------------------------------------------------------------------
// 4. Rust-side outputs: registry.rs and the capabilities
// ---------------------------------------------------------------------------

function registryRs(manifest) {
  const paths = manifest.commands.map((c) => `        crate::commands::${c.module}::${c.name},`).join('\n');
  const names = manifest.commands.map((c) => `    "${c.name}",`).join('\n');
  return `//! GENERATED by \`scripts/gen-ipc.mjs\` from \`contract/ipc_manifest.rs\`. Do not edit.
//!
//! The invoke handler: exactly the commands of the manifest, in manifest order
//! (contract §4.1 rule 2). A command that is not listed here is not invocable,
//! and \`build.rs\` feeds the same list to the capability manifest.

/// The \`generate_handler!\` list of every manifest command.
pub fn handler<R: tauri::Runtime>() -> impl Fn(tauri::ipc::Invoke<R>) -> bool + Send + Sync + 'static {
    tauri::generate_handler![
${paths}
    ]
}

/// The command names registered by [\`handler\`], in manifest order.
pub const REGISTERED: &[&str] = &[
${names}
];
`;
}

function capabilities(manifest) {
  const main = {
    $schema: '../gen/schemas/desktop-schema.json',
    identifier: 'main',
    description:
      'The main window: event listen, window drag/title and exactly the v1 command manifest (contract §9.2). GENERATED by scripts/gen-ipc.mjs from contract/ipc_manifest.rs.',
    windows: ['main'],
    permissions: [
      ...manifest.corePermissions,
      ...manifest.commands.filter((c) => c.capability === 'main').map((c) => c.permission),
    ],
  };
  const debug = {
    $schema: '../gen/schemas/desktop-schema.json',
    identifier: 'debug',
    description:
      'Debug-only commands; build.rs includes this file only in debug builds (contract §4.1 rule 2). GENERATED by scripts/gen-ipc.mjs from contract/ipc_manifest.rs.',
    windows: ['main'],
    permissions: manifest.commands.filter((c) => c.capability === 'debug').map((c) => c.permission),
  };
  return {
    [CAP_MAIN]: JSON.stringify(main, null, 2) + '\n',
    [CAP_DEBUG]: JSON.stringify(debug, null, 2) + '\n',
  };
}

// ---------------------------------------------------------------------------
// 5. assemble, write or compare
// ---------------------------------------------------------------------------

function build() {
  const outputs = new Map();
  const work = mkdtempSync(join(tmpdir(), 'gilde-gen-ipc-'));
  try {
    let manifest;
    let tsDir = null;
    if (manifestArg) {
      manifest = JSON.parse(readFileSync(manifestArg, 'utf8'));
    } else {
      ({ tsDir, manifest } = runCargo(work));
    }

    outputs.set(REGISTRY, registryRs(manifest));
    for (const [p, text] of Object.entries(capabilities(manifest))) outputs.set(p, text);

    if (tsDir) {
      const typeFiles = walk(tsDir)
        .filter((p) => p.endsWith('.ts'))
        .map((p) => relative(tsDir, p).split(sep).join('/'))
        .sort();
      if (typeFiles.length === 0) die('ts-rs exported no types');
      for (const rel of typeFiles) {
        const text = processType(rel, readFileSync(join(tsDir, rel), 'utf8'));
        outputs.set(`${GEN_TS}/${rel}`, text);
        outputs.set(`${GEN_SIDECAR}/${rel}`, text);
      }
      outputs.set(`${GEN_TS}/commands.ts`, commandsTs(manifest));
      outputs.set(`${GEN_TS}/events.ts`, eventsTs(manifest));
      outputs.set(`${GEN_TS}/index.ts`, indexTs(typeFiles, true));
      outputs.set(`${GEN_SIDECAR}/index.ts`, indexTs(typeFiles, false));
      outputs.set(`${GEN_TS}/tsconfig.json`, JSON.stringify(GEN_TSCONFIG, null, 2) + '\n');
    }
    return { outputs, ownsGenDirs: Boolean(tsDir) };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

function listDir(dirRel) {
  const abs = join(root, dirRel);
  if (!existsSync(abs)) return [];
  return walk(abs).map((p) => relative(root, p).split(sep).join('/'));
}

function main() {
  const { outputs, ownsGenDirs } = build();
  const genDirs = ownsGenDirs ? [GEN_TS, GEN_SIDECAR] : [];

  if (check) {
    const drift = [];
    for (const [rel, text] of outputs) {
      const abs = join(root, rel);
      if (!existsSync(abs)) drift.push(`missing   ${rel}`);
      else if (readFileSync(abs, 'utf8') !== text) drift.push(`differs   ${rel}`);
    }
    for (const dir of genDirs) {
      for (const rel of listDir(dir)) if (!outputs.has(rel)) drift.push(`extra     ${rel}`);
    }
    if (drift.length) {
      console.error(`[gen-ipc] generated files are out of date (${drift.length}):\n  ${drift.join('\n  ')}`);
      console.error('[gen-ipc] run `node scripts/gen-ipc.mjs` and commit the result.');
      process.exit(1);
    }
    console.log(`[gen-ipc] up to date (${outputs.size} files checked).`);
  } else {
    for (const dir of genDirs) rmSync(join(root, dir), { recursive: true, force: true });
    for (const [rel, text] of outputs) {
      const abs = join(root, rel);
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, text);
    }
    console.log(`[gen-ipc] wrote ${outputs.size} files.`);
  }

  if (typecheck) {
    try {
      execFileSync(join(root, 'node_modules', '.bin', 'tsc'), ['-p', join(root, GEN_TS)], {
        cwd: root,
        stdio: 'inherit',
      });
      console.log('[gen-ipc] generated TypeScript type-checks in isolation.');
    } catch {
      die('the generated TypeScript does not type-check (tsc -p src/lib/gen)');
    }
  }
}

main();
