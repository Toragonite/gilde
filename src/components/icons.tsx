/**
 * Icons — inline Lucide (MIT) paths, one file, no dependency, no icon font and
 * no emoji (UI-GUIDELINES §2-3).
 *
 * 16px, `stroke-width: 1.5`, `currentColor`, so an icon takes the colour of the
 * row it sits in. Agents are never drawn as logos: they are text badges
 * (`claude`, `codex`, `cursor`, `agy`).
 */

import type { SVGProps } from 'react';

export interface IconProps extends SVGProps<SVGSVGElement> {
  /** `sm` renders at 14px for dense rows. */
  size?: 'sm' | 'md';
}

function Svg({ size = 'md', className, children, ...rest }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      className={['i', size === 'sm' ? 'sm' : '', className ?? ''].filter(Boolean).join(' ')}
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  );
}

